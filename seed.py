def seed(include_test_users=True):
    app = create_app()
    with app.app_context():
        db.create_all()
        for name in ('Сумки', 'Кошельки', 'Ремни', 'Обложки', 'Аксессуары'):
            if not db.session.query(ProductCategory).filter_by(name=name).first(): db.session.add(ProductCategory(name=name))
        for name in ARTICLES:
            if not db.session.query(ArticleCategory).filter_by(name=name).first(): db.session.add(ArticleCategory(name=name))
        db.session.commit()
        categories = {item.name: item.id for item in db.session.query(ProductCategory)}
        article_categories = {item.name: item.id for item in db.session.query(ArticleCategory)}
        for index, (name, category, short, description, material, price, stock) in enumerate(PRODUCTS, 1):
            image = f'product{index:02d}.webp'
            existing = db.session.query(Product).filter_by(image=image).first()
            if existing:
                existing.name = name
                existing.short_description = short
                existing.description = description
                existing.material = material
            elif not db.session.query(Product).filter_by(name=name).first():
                db.session.add(Product(name=name, category_id=categories[category], short_description=short, description=description, material=material, price=price, stock=stock, image=f'product{index:02d}.webp'))
        for category, entries in ARTICLES.items():
            for title, short, content in entries:
                existing = db.session.query(Article).filter_by(title=title).first()
                if existing:
                    existing.image = ARTICLE_IMAGES[title]
                else:
                    db.session.add(Article(title=title, category_id=article_categories[category], short_description=short, content=content, image=ARTICLE_IMAGES[title], author='Редакция мастерской', published=True))
        for title, short, content in NEWS:
            existing = db.session.query(News).filter_by(title=title).first()
            if existing:
                existing.image = NEWS_IMAGES[title]
            else:
                db.session.add(News(title=title, short_description=short, content=content, image=NEWS_IMAGES[title], author='Мастерская'))
        if include_test_users:
            for name, email, password, role in [('Тестовый пользователь', 'user@example.com', 'User123!', 'user'), ('Сотрудник', 'employee@example.com', 'Employee123!', 'employee')]:
                if not db.session.query(User).filter_by(email=email).first():
                    db.session.add(User(name=name, email=email, password_hash=generate_password_hash(password), role=role))
        db.session.commit()
        print('База заполнена:', db.session.query(Product).count(), 'товаров,', db.session.query(Article).count(), 'статей,', db.session.query(News).count(), 'новостей')


if __name__ == '__main__': seed()
